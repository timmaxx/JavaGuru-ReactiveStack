package by.javaguru.users.service;

import by.javaguru.users.data.UserEntity;
import by.javaguru.users.service.dto.CreateUserDto;
import by.javaguru.users.service.dto.UserDto;
import org.mapstruct.Builder;
import org.mapstruct.Mapper;
import org.mapstruct.ReportingPolicy;

//  https://habr.com/ru/articles/818489/
//  https://javarush.com/groups/posts/3698-chto-takoe-mapstruct-i-kak-praviljhno-nastroitjh-ego-dlja-moduljhnogo-testirovanija-v-springboo

@Mapper(unmappedTargetPolicy = ReportingPolicy.IGNORE, componentModel = "spring",
        builder = @Builder(disableBuilder = true))
//  After compilation You can see generated by MapStruct java classes in folder target/generated-sources/annotations.
public interface UserMapper {

    UserEntity createUserDtoToUserEntity(CreateUserDto createUserDto);

    UserDto userEntityToUserDto(UserEntity userEntity);

}
